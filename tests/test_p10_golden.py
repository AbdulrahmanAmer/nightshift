def test_a_one_character_change_in_a_golden_file_would_fail(built: dict[str, str]) -> None:
    """The comparison is exact: the same text with one character changed is not equal."""
    text = golden("story_graph_dark_slowzoom")
    assert built["story_graph_dark_slowzoom"] == text
    assert built["story_graph_dark_slowzoom"] != text.replace("1080x1920", "1080x1921", 1)
    assert Path(mg.GOLDEN_DIR / "make_golden.py").exists()
