"""Package P10: the shipped presets keep producing today's filter graphs and ASS files.

The files in `tests/golden/p10/` were generated by `tests/golden/p10/make_golden.py` on origin/main d50d4ad,
before formats became data in the renderer. Every case here rebuilds one text and compares it with its file; a
change of one character in either side fails the test. All cases are pure (no FFmpeg).
"""

