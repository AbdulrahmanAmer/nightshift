"""Package P10b: the shipped long and square presets keep producing today's chapter render and captions.

The files in `tests/golden/p10b/` were generated by `tests/golden/p10b/make_golden.py` on origin/main d890afa
(P10a merged, full videos not yet reading their format). Every case rebuilds one text and compares it with
its file. All cases are pure: the chapter render runs against a recording stand-in for FFmpeg.
"""

from __future__ import annotations

import os
from collections.abc import Iterator
from pathlib import Path

import pytest

from tests.golden.p10b import make_golden as mg


@pytest.fixture(scope="module")
def built(tmp_path_factory: pytest.TempPathFactory) -> Iterator[dict[str, str]]:
    """Every case, built once per module on an empty home (no owner formats)."""
    root = tmp_path_factory.mktemp("golden-b")
    (root / "home").mkdir()
    saved = os.environ.get("NIGHTSHIFT_HOME")
    os.environ["NIGHTSHIFT_HOME"] = str(root / "home")
    try:
        yield mg.cases(root)
    finally:
        if saved is None:
            os.environ.pop("NIGHTSHIFT_HOME", None)
        else:
            os.environ["NIGHTSHIFT_HOME"] = saved


def golden(stem: str) -> str:
    return (mg.GOLDEN_DIR / f"{stem}.txt").read_text(encoding="utf-8").replace("\r\n", "\n")


def stems(prefix: str) -> list[str]:
    return sorted(p.stem for p in mg.GOLDEN_DIR.glob(f"{prefix}*.txt"))


def test_the_golden_folder_holds_every_case(built: dict[str, str]) -> None:
    assert sorted(built) == sorted(p.stem for p in mg.GOLDEN_DIR.glob("*.txt"))
    assert len(built) >= 15


@pytest.mark.parametrize("stem", stems("master_command_"))
def test_the_chapter_render_of_the_shipped_long_preset_matches_origin_main(
    built: dict[str, str], stem: str
) -> None:
    """FFmpeg arguments, title-card colour source, filter graph and card captions of a chapter."""
    assert built[stem] == golden(stem)


@pytest.mark.parametrize("stem", stems("long_band_"))
def test_the_long_caption_band_matches_origin_main(built: dict[str, str], stem: str) -> None:
    assert built[stem] == golden(stem)


@pytest.mark.parametrize("stem", stems("square_"))
def test_the_shipped_square_preset_matches_origin_main(built: dict[str, str], stem: str) -> None:
    """The square as a Short draws it since P10a: story graph, caption file and caption band."""
    assert built[stem] == golden(stem)


def test_a_one_character_change_in_a_golden_file_would_fail(built: dict[str, str]) -> None:
    text = golden("master_command_card_cinematic_teal")
    assert built["master_command_card_cinematic_teal"] == text
    assert built["master_command_card_cinematic_teal"] != text.replace("s=1920x1080", "s=1920x1081", 1)
    assert Path(mg.GOLDEN_DIR / "make_golden.py").exists()
